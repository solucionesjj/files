// Karma configuration for the Angular application builder (`@angular/build:karma`).
// Kept minimal and self-contained: the builder injects its own asset/polyfill middleware and
// strips the legacy `@angular-devkit/build-angular` framework, so only the jasmine/chrome/coverage
// plugins are declared here. `ChromeHeadlessNoSandbox` runs headless Chrome without the sandbox so
// the suite works on CI runners and macOS (where Chrome's sandbox cannot initialize).
module.exports = function (config) {
  config.set({
    basePath: '',
    frameworks: ['jasmine'],
    plugins: [
      require('karma-jasmine'),
      require('karma-chrome-launcher'),
      require('karma-jasmine-html-reporter'),
      require('karma-coverage'),
    ],
    client: {
      jasmine: {},
      clearContext: false,
    },
    jasmineHtmlReporter: {
      suppressAll: true,
    },
    coverageReporter: {
      dir: require('path').join(__dirname, './coverage/web'),
      subdir: '.',
      reporters: [{ type: 'html' }, { type: 'text-summary' }],
    },
    reporters: ['progress', 'kjhtml'],
    browsers: ['ChromeHeadlessNoSandbox'],
    customLaunchers: {
      ChromeHeadlessNoSandbox: {
        base: 'ChromeHeadless',
        flags: ['--no-sandbox', '--headless', '--disable-gpu', '--disable-dev-shm-usage'],
      },
    },
    restartOnFileChange: true,
  });
};
